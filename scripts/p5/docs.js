#!/usr/bin/env node

const fs = require('fs');
const path = require('path');

const P5_SOURCE = process.env.P5_SOURCE_DIR || '/tmp/p5.js';
const outputDir = 'doc';

if (!fs.existsSync(outputDir)) {
  fs.mkdirSync(outputDir, { recursive: true });
}

function asText(value) {
  if (value == null) return '';
  if (typeof value === 'string') return value;
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  if (Array.isArray(value)) return value.map(asText).filter(Boolean).join(' ');
  if (typeof value === 'object') {
    if (typeof value.value === 'string') return value.value;
    if (typeof value.description === 'string') return value.description;
    if (Array.isArray(value.children)) return value.children.map(asText).filter(Boolean).join(' ');
    try {
      return JSON.stringify(value);
    } catch {
      return '';
    }
  }
  return String(value);
}

function wrapText(text, maxLength = 78) {
  const normalized = asText(text).replace(/\s+/g, ' ').trim();
  if (!normalized || normalized.length <= maxLength) return normalized;
  const words = normalized.split(' ');
  const lines = [];
  let currentLine = '';
  for (const word of words) {
    if ((currentLine + ' ' + word).trim().length <= maxLength) {
      currentLine = (currentLine + ' ' + word).trim();
    } else {
      if (currentLine) lines.push(currentLine);
      currentLine = word;
    }
  }
  if (currentLine) lines.push(currentLine);
  return lines.join('\n');
}

const moduleEmojis = {
  'accessibility': '♿',
  'color': '🎨',
  'core': '⚙️',
  'data': '📊',
  'dom': '🌐',
  'events': '🖱️',
  'image': '🖼️',
  'io': '📁',
  'math': '🔢',
  'typography': '📝',
  'utilities': '🛠️',
  'webgl': '🎮',
  'webgpu': '💠',
  'type': '🔤',
  'shape': '🔷',
};

function createVimdocContent(moduleName, functions, p5Version, timestamp) {
  const emoji = moduleEmojis[moduleName] || '📚';
  const tocFunctions = functions.map(func =>
    `  - ${func.name}()              |p5-${moduleName}-${func.name}|`
  ).join('\n');

  const functionDocs = functions.map(func => {
    const cleanDesc = func.description || '';
    const wrappedDesc = wrapText(cleanDesc);

    let paramsSection = '';
    if (func.params && func.params.length > 0) {
      const paramsList = func.params.map(p => {
        const cleanParamDesc = p.description || '';
        return `    ${p.name}  ${cleanParamDesc}`;
      }).join('\n');
      paramsSection = `
#### Parameters:

${paramsList}
`;
    }

    const cleanReturn = func.returns || 'void';

    return `
\`${func.name}()\`                                            |p5-${moduleName}-${func.name}|

${wrappedDesc}
${paramsSection}
#### Returns:

    ${cleanReturn}

📂 *Sub-module: ${func.subModule || 'main'}*

---
`;
  }).join('\n');

  return `*p5-${moduleName}*                                         p5.js ${moduleName} docs

==============================================================================
Table of Contents                           *p5-${moduleName}-table-of-contents*

1. Functions                                                |p5-${moduleName}-functions|
${tocFunctions}

${emoji} ${moduleName.charAt(0).toUpperCase() + moduleName.slice(1)} module for p5.js

📦 p5.js Version: ${p5Version}~
⏰ Last Updated: ${timestamp}~

==============================================================================
2. Functions                                                |p5-${moduleName}-functions|

${functionDocs}
==============================================================================
Autogenerated by automata <https://github.com/prjctimg/automata>

vim:tw=78:ts=8:ft=help:norl:
`;
}

function extractDocumentation() {
  const dataPath = path.join(P5_SOURCE, 'docs', 'data.json');

  if (!fs.existsSync(dataPath)) {
    console.error('❌ Documentation data.json not found at:', dataPath);
    console.error('   Run `npx documentation build` on p5.js source first.');
    process.exit(1);
  }

  const pkgPath = path.join(P5_SOURCE, 'package.json');
  let p5Version = process.env.P5_VERSION || 'unknown';
  if (fs.existsSync(pkgPath)) {
    const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
    p5Version = pkg.version || p5Version;
  }
  const timestamp = new Date().toISOString().replace('T', ' ').replace(/\.\d+/, '');

  console.log('📖 Reading documentation data.json...');
  const raw = fs.readFileSync(dataPath, 'utf8');
  const entries = JSON.parse(raw);

  const modules = {};

  for (const entry of entries) {
    if (entry.kind !== 'function') continue;
    if (!entry.name) continue;

    const filePath = entry.path || [];
    const moduleName = filePath.length >= 2 ? filePath[1] : 'core';

    const description = asText(entry.description).replace(/\s+/g, ' ').trim();

    const params = [];
    const returns = [];

    if (entry.tags) {
      for (const tag of entry.tags) {
        if (tag.title === 'param') {
          params.push({
            name: tag.name || '',
            description: asText(tag.description).replace(/\s+/g, ' ').trim(),
          });
        } else if (tag.title === 'return' || tag.title === 'returns') {
          returns.push(asText(tag.description).replace(/\s+/g, ' ').trim());
        }
      }
    }

    if (!modules[moduleName]) {
      modules[moduleName] = [];
    }

    modules[moduleName].push({
      name: entry.name,
      description,
      params,
      returns: returns.join(', ') || 'void',
      subModule: filePath.length >= 3 ? filePath[2].replace('.js', '') : '',
    });
  }

  console.log(`📊 Found ${Object.keys(modules).length} modules with ${Object.values(modules).reduce((t, f) => t + f.length, 0)} functions`);

  for (const [moduleName, functions] of Object.entries(modules)) {
    // Plugin help is owned by p5.nvim — never overwrite
    if (moduleName === 'nvim') {
      console.log('  ⏭️  skipping reserved module name: nvim');
      continue;
    }
    const vimdoc = createVimdocContent(moduleName, functions, p5Version, timestamp);
    fs.writeFileSync(path.join(outputDir, `p5-${moduleName}.txt`), vimdoc);
    console.log(`  ✅ p5-${moduleName}.txt (${functions.length} functions)`);
  }

  const indexContent = `*p5-modules*                                         p5.js modules index

==============================================================================
Table of Contents                                  *p5-modules-table-of-contents*

1. Available Modules                                      |p5-modules-available|

📚 p5.js Modules Documentation

📦 p5.js Version: ${p5Version}~
⏰ Last Updated: ${timestamp}~

==============================================================================
1. Available Modules                                      |p5-modules-available|

${Object.entries(modules).map(([moduleName, functions]) => {
  const emoji = moduleEmojis[moduleName] || '📚';
  return `- ${emoji} p5.${moduleName} - ${functions.length} functions`;
}).join('\n')}

Total: ${Object.values(modules).reduce((total, funcs) => total + funcs.length, 0)} functions across ${Object.keys(modules).length} modules

==============================================================================
Autogenerated by automata <https://github.com/prjctimg/automata>

vim:tw=78:ts=8:ft=help:norl:
`;

  fs.writeFileSync(path.join(outputDir, 'p5-modules.txt'), indexContent);
  console.log('✅ Index file generated');
}

try {
  extractDocumentation();
  console.log('🎉 Vimdoc documentation generation complete!');
} catch (error) {
  console.error('❌ Error generating documentation:', error.message);
  process.exit(1);
}
